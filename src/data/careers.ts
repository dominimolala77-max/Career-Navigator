export function matchCareers(profile: {
  apsScore: number;
  subjects: string[];
  personalityType: string;
  preferredFields: string[];
}): Career[] {
  const { apsScore, subjects, personalityType, preferredFields } = profile;

  return CAREERS
    .filter(c => {
      if (apsScore > 0 && c.minAps > apsScore + 5) return false;
      return true;
    })
    .map(c => {
      let score = 0;
      if (apsScore >= c.minAps) score += 30;
      else if (apsScore >= c.minAps - 5) score += 15;

      const subjectMatch = c.requiredSubjects.filter(s => subjects.includes(s)).length;
      score += subjectMatch * 20;

      if (c.personalityTypes.includes(personalityType)) score += 25;

      if (preferredFields.some(f => c.field.toLowerCase().includes(f.toLowerCase()))) score += 20;

      return { career: c, score };
    })
    .sort((a, b) => b.score - a.score)
    .map(({ career }) => career);
}
