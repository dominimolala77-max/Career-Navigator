export function getBursariesByField(field: string): Bursary[] {
  return BURSARIES.filter(b =>
    b.fields.some(f => f.toLowerCase().includes(field.toLowerCase()))
  );
}

export function getOpenBursaries(): Bursary[] {
  return BURSARIES.filter(b => b.status === "open");
}
